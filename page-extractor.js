(() => {
  const emit = (detail) => window.dispatchEvent(
    new CustomEvent("youtube-caption-spike-result", { detail }),
  );

  const getPlayerResponse = () => {
    const player = document.querySelector("#movie_player");
    return player?.getPlayerResponse?.() || window.ytInitialPlayerResponse;
  };

  const textFromEvent = (event) => (event.segs || [])
    .map((segment) => segment.utf8 || "")
    .join("")
    .replace(/\n/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  async function extract() {
    const response = getPlayerResponse();
    const tracks = response?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
    const track = tracks.find(({ languageCode }) => /^en(?:-|$)/i.test(languageCode));
    if (!track) throw new Error("No English caption track in player response");

    const endpoint = new URL(track.baseUrl);
    endpoint.searchParams.set("fmt", "json3");
    const timedText = await fetch(endpoint, { credentials: "include" });
    if (!timedText.ok) throw new Error(`timedtext returned HTTP ${timedText.status}`);
    const payload = await timedText.json();
    const cues = (payload.events || [])
      .filter((event) => event.tStartMs != null && event.dDurationMs != null)
      .map((event) => ({
        start: event.tStartMs / 1000,
        duration: event.dDurationMs / 1000,
        text: textFromEvent(event),
      }))
      .filter(({ text }) => text);

    emit({
      videoId: response.videoDetails?.videoId,
      title: response.videoDetails?.title,
      track: {
        languageCode: track.languageCode,
        name: track.name?.simpleText || track.name?.runs?.map((run) => run.text).join(""),
        isAutoGenerated: track.kind === "asr",
      },
      cueCount: cues.length,
      cues,
    });
  }

  // Navigation can finish after document_idle; retry briefly without retaining a
  // long-lived observer in this intentionally minimal spike.
  let attempts = 0;
  const run = () => extract().catch((error) => {
    attempts += 1;
    if (attempts < 10 && /player response/i.test(error.message)) {
      setTimeout(run, 500);
    } else {
      emit({ error: error.message });
    }
  });
  run();
})();
